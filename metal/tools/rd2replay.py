#!/usr/bin/env python3
"""Turn a turnip FD_RD_DUMP=full capture into a C header the kernel can replay.

  rd2replay.py CAPTURE.rd PREFIX [--gen VA ...] > header.h

The kernel maps one span of GPU addresses [PREFIX_VA_START, PREFIX_VA_END), zero-fills it,
copies the listed non-zero pages in at their addresses and then runs PREFIX_cmds[] as
indirect buffers, in order. A buffer named with --gen is left out of the page list: the
kernel fills it itself (a texture, say), which keeps the header small.
"""
import argparse, gzip, struct, sys

ap = argparse.ArgumentParser()
ap.add_argument('rd'); ap.add_argument('prefix')
ap.add_argument('--gen', action='append', default=[], type=lambda s: int(s, 0))
a = ap.parse_args()

d = open(a.rd, 'rb').read()
if d[:2] == b'\x1f\x8b':
    d = gzip.decompress(d)
bos, cmds, o, cur, chip = [], [], 0, None, 0
while o < len(d):
    t, s = struct.unpack_from('<II', d, o); o += 8; p = d[o:o + s]; o += s
    if t == 3:                                   # RD_GPUADDR
        lo, sz, hi = struct.unpack('<III', p); cur = [hi << 32 | lo, sz, None]; bos.append(cur)
    elif t == 12:                                # RD_BUFFER_CONTENTS, for the last GPUADDR
        cur[2] = p
    elif t == 6:                                 # RD_CMDSTREAM_ADDR
        lo, sz, hi = struct.unpack('<III', p); cmds.append((hi << 32 | lo, sz))
    elif t == 14:                                # RD_CHIP_ID
        chip = struct.unpack_from('<Q', p)[0]
if not cmds:
    sys.exit('no command stream in the capture')
start = min(b[0] for b in bos); end = max(b[0] + b[1] for b in bos)
if end > 1 << 32:
    sys.exit('capture is above 4 GB: run it with FD_VA_START/FD_VA_SIZE below')
pages = []
for va, sz, data in bos:
    if va in a.gen:
        continue
    if data is None:
        sys.exit('buffer %x has no contents: capture with FD_RD_DUMP=full' % va)
    for off in range(0, sz, 4096):
        pg = data[off:off + 4096].ljust(4096, b'\0')
        if any(pg):
            pages.append((va + off, pg))
P = a.prefix
w = sys.stdout.write
w('/* generated by metal/tools/rd2replay.py from %s: chip %x, do not edit */\n' % (a.rd.split('/')[-1], chip))
w('#define %s_VA_START 0x%xu\n#define %s_VA_END 0x%xu\n' % (P, start, P, end))
w('static const struct { uint32_t va, size; } %s_bos[] = {\n' % P)
for va, sz, _ in bos:
    w('\t{ 0x%08x, 0x%x },%s\n' % (va, sz, ' /* generated */' if va in a.gen else ''))
w('};\nstatic const struct { uint32_t va, dwords; } %s_cmds[] = {\n' % P)
for va, n in cmds:
    w('\t{ 0x%08x, %u },\n' % (va, n))
w('};\nstatic const uint32_t %s_page_va[%u] = {\n' % (P, len(pages)))
for va, _ in pages:
    w('\t0x%08x,\n' % va)
w('};\n/* each page as runs: (dword index, count, values...), ended by 0xffffffff */\n')
w('static const uint32_t %s_page_runs[] = {\n' % P)
total = 0
for va, pg in pages:
    dw = struct.unpack('<1024I', pg); i = 0
    w('\t/* %08x */\n' % va)
    while i < 1024:
        if dw[i] == 0:
            i += 1; continue
        j = i
        while j < 1024 and (dw[j] != 0 or (j + 1 < 1024 and dw[j + 1] != 0)):
            j += 1
        vals = dw[i:j]; total += 2 + len(vals)
        w('\t%u, %u,' % (i, len(vals)))
        for k in range(0, len(vals), 8):
            w(('\n\t\t' if k else ' ') + ' '.join('0x%08x,' % v for v in vals[k:k + 8]))
        w('\n'); i = j
    w('\t0xffffffff,\n'); total += 1
w('};\n')
print('%d buffers, %d command streams, %d non-zero pages, %d dwords of runs' % (len(bos), len(cmds), len(pages), total), file=sys.stderr)
