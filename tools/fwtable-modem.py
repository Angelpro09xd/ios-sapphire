#!/usr/bin/env python3
"""C tables of the files in a phone's modem_a (FAT16) for TopazModem.cpp.

    tools/fwtable-modem.py modem_a.img PHONE > tables.inc

modem_a.img is a read-only dump of the partition (adb: dd if=/dev/block/
by-name/modem_a). Emits fw_ext_PHONE[] (byte offset in the partition and
length of each run of clusters), fw_all_PHONE[] (lower-case path under
image/, size, first extent, extent count) and fw_files_PHONE[] (the modem
image, offset/size/CRC32 of each one-extent file) in the formats the
driver uses.
"""
import struct
import sys
import zlib

img, phone = sys.argv[1], sys.argv[2]
d = open(img, 'rb').read()
bps, spc, rsv, nfat, nroot, _, _, spf = struct.unpack_from('<HBHBHHBH', d, 11)
fat_off = rsv * bps
root_off = fat_off + nfat * spf * bps
data_off = root_off + ((nroot * 32 + bps - 1) // bps) * bps
csize = spc * bps
fat = d[fat_off:fat_off + spf * bps]


def chain(c):
    out = []
    while 2 <= c < 0xfff8:
        out.append(c)
        c = struct.unpack_from('<H', fat, c * 2)[0]
    return out


def entries(raw):
    lfn = []
    for i in range(0, len(raw), 32):
        e = raw[i:i + 32]
        if e[0] == 0:
            break
        if e[0] == 0xe5:
            lfn = []
            continue
        if e[11] == 0x0f:
            part = (e[1:11] + e[14:26] + e[28:32]).decode('utf-16le', 'ignore').split('\x00')[0]
            lfn.insert(0, part)
            continue
        if e[11] & 0x08:                    # volume label
            lfn = []
            continue
        base, ext = e[0:8].decode().strip(), e[8:11].decode().strip()
        name = ''.join(lfn) or (base + ('.' + ext if ext else ''))
        lfn = []
        yield name, e[11], struct.unpack_from('<H', e, 26)[0], struct.unpack_from('<I', e, 28)[0]


def dirdata(c):
    return b''.join(d[data_off + (x - 2) * csize:data_off + (x - 1) * csize] for x in chain(c))


def walk(raw, path):
    for name, attr, c, size in entries(raw):
        if name in ('.', '..'):
            continue
        if attr & 0x10:
            yield from walk(dirdata(c), path + name + '/')
        else:
            yield path + name, c, size


files = []
for p, c, size in walk(d[root_off:data_off], ''):
    p = p.lower()
    if not p.startswith('image/'):
        continue
    runs = []
    for x in chain(c) if size else []:
        off = data_off + (x - 2) * csize
        if runs and runs[-1][0] + runs[-1][1] == off:
            runs[-1][1] += csize
        else:
            runs.append([off, csize])
    left = size                             # trim the last run to the file size
    for r in runs:
        r[1] = min(r[1], left)
        left -= r[1]
    runs = [r for r in runs if r[1]]
    data = b''.join(d[o:o + n] for o, n in runs)
    files.append((p, size, runs, zlib.crc32(data)))

next = sum(len(r) for _, _, r, _ in files)
print(f'/* generated by tools/fwtable-modem.py from {phone} modem_a: {len(files)} files, {next} extents */')
print(f'static const struct fw_extent fw_ext_{phone}[] = {{')
for _, _, runs, _ in files:
    for o, n in runs:
        print(f'\t{{ {o:#x}, {n:#x} }},')
print('};')
print(f'static const struct fw_all_file fw_all_{phone}[] = {{')
k = 0
for p, size, runs, _ in files:
    print(f'\t{{ "{p}", {size:#x}, {k}, {len(runs)} }},')
    k += len(runs)
print('};')
print(f'static const struct fw_file fw_files_{phone}[] = {{')
for p, size, runs, crc in sorted(files):
    name = p[len('image/'):]
    if name.startswith('modem.') and '/' not in name:
        assert len(runs) == 1, p
        print(f'\t{{ "{name}", {runs[0][0]:#x}, {size:#x}, {crc:#010x} }},')
print('};')
