#!/usr/bin/env python3
"""gen_decomp.py > decomp.h: HFS+ canonical decompositions (TN1150). HFS+ froze its decomposition at Unicode 3.2
(Python keeps that data as unicodedata.ucd_3_2_0). BMP only, except U+2000-U+2FFF and U+F900-U+FAFF; Hangul
syllables are decomposed algorithmically in mkhfs.c."""
import unicodedata
u = unicodedata.ucd_3_2_0
rows = []
for cp in range(0xC0, 0x10000):
    if 0x2000 <= cp <= 0x2FFF or 0xF900 <= cp <= 0xFAFF or 0xAC00 <= cp <= 0xD7A3 or 0xD800 <= cp <= 0xDFFF:
        continue
    d = u.normalize("NFD", chr(cp))
    if d != chr(cp) and all(ord(c) < 0x10000 for c in d):
        rows.append((cp, [ord(c) for c in d]))
m = max(len(r[1]) for r in rows)
print("/* generated by gen_decomp.py: HFS+ canonical decompositions (TN1150, Unicode 3.2) */")
print("#define DECOMP_MAX %d" % m)
print("static const struct { unsigned short cp, n, d[%d]; } decomp_table[] = {" % m)
for cp, ds in rows:
    print("\t{0x%04x, %d, {%s}}," % (cp, len(ds), ", ".join("0x%04x" % c for c in ds)))
print("};")
